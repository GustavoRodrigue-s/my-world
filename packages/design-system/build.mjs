// Builds the design tokens (DTCG 2025.10 JSON in tokens/) into what the web
// app consumes, with Style Dictionary:
//
//   generated/css/tokens.css      shared tokens on :root (type, space, size, radius, motion, layers)
//   generated/css/tailwind-breakpoints.css   the breakpoints as Tailwind @theme literals
//   generated/css/<theme>.css     one environment's colors and shadow, scoped to [data-env="<theme>"], day/night/print
//   generated/tokens.json         every resolved value, for code that needs a literal (swatches)
//   generated/brand/*.svg         the mark as standalone files (favicon, downloads, slides, avatars)
//
//   pnpm --filter @my-world/design-system build   (or `pnpm tokens` at the root)
//
// The tokens are written in px and ms. The web is where they become responsive:
// type, space, sizes and breakpoints turn into rem (so they follow the reader's
// browser font size), and roles with a `world.fluid` extension grow with the
// viewport (clamp). Hairlines, corners and shadows stay in px.
//
// Another platform (iOS, Android, Figma…) is another entry in `platforms`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import StyleDictionary from 'style-dictionary'
import { MARK_GEOMETRY as g, MARK_ORBIT_PATH, markSatellitePath } from './src/mark.ts'

// Paths below are relative to this package, wherever the build is run from.
process.chdir(fileURLToPath(new URL('.', import.meta.url)))

const THEMES = ['portfolio', 'chapel', 'blog']
const SOURCES = ['base', ...THEMES]
const HEADER = (source) => [
  `/* Generated by Style Dictionary from packages/design-system/tokens/${source} — do not edit. */`,
  '/* To update: edit the JSON, then `pnpm tokens`. */',
]

// 1rem = the reader's browser font size, 16px by default (<html> sets none).
const ROOT_PX = 16
// Token groups whose px become rem on the web.
const REM_GROUPS = ['font', 'space', 'size', 'breakpoint']

const round = (n, digits = 6) => +n.toFixed(digits)
const rem = (px, root = ROOT_PX) => `${round(px / root)}rem`

// A DTCG color keeps both `components` (what the spec reads) and `hex` (what a
// person edits). Refuse to build if someone changed one and not the other.
function checkColors(node, path = []) {
  if (node && typeof node === 'object') {
    const v = node.$value
    if (v && typeof v === 'object' && v.hex && v.components) {
      const hex = '#' + v.components.map((c) => Math.round(c * 255).toString(16).padStart(2, '0')).join('')
      if (hex.toLowerCase() !== v.hex.toLowerCase()) {
        throw new Error(`${path.join('.')}: hex ${v.hex} doesn't match components (${hex}). Update both.`)
      }
    }
    for (const [k, child] of Object.entries(node)) if (!k.startsWith('$')) checkColors(child, [...path, k])
  }
}
for (const file of SOURCES) checkColors(JSON.parse(readFileSync(`tokens/${file}.json`, 'utf8')))

const dimension = (v, root) =>
  typeof v === 'object' ? (root && v.unit === 'px' ? rem(v.value, root) : `${v.value}${v.unit}`) : v
const rootFor = (t) => (REM_GROUPS.includes(t.path[0]) ? ROOT_PX : undefined)

StyleDictionary.registerTransform({
  name: 'world/dimension',
  type: 'value',
  filter: (t) => t.$type === 'dimension',
  transform: (t) => dimension(t.$value, rootFor(t)),
})

// letter-spacing and font.scale are fractions of the font size; on the web, em.
StyleDictionary.registerTransform({
  name: 'world/letter-spacing',
  type: 'value',
  filter: (t) => t.path[0] === 'font' && ['letter-spacing', 'scale'].includes(t.path[1]),
  transform: (t) => `${t.$value}em`,
})

// DTCG has no angle type: rotations are numbers in degrees.
StyleDictionary.registerTransform({
  name: 'world/angle',
  type: 'value',
  filter: (t) => t.path[0] === 'transform' && t.path[1] === 'rotate',
  transform: (t) => `${t.$value}deg`,
})

StyleDictionary.registerTransform({
  name: 'world/duration',
  type: 'value',
  filter: (t) => t.$type === 'duration',
  transform: (t) => `${t.$value.value}${t.$value.unit}`,
})

StyleDictionary.registerTransform({
  name: 'world/shadow',
  type: 'value',
  transitive: true,
  filter: (t) => t.$type === 'shadow',
  transform: ({ $value: s }) =>
    typeof s === 'string' ? s : [s.offsetX, s.offsetY, s.blur, s.spread].map((d) => dimension(d)).join(' ') + ` ${s.color}`,
})

const TRANSFORMS = ['name/kebab', 'world/dimension', 'world/letter-spacing', 'world/angle', 'world/duration', 'color/css', 'fontFamily/css', 'cubicBezier/css', 'world/shadow']

// `{font.weight.semibold}` → var(--font-weight-semibold); a literal → its CSS value.
const lookup = (dictionary, ref) => dictionary.allTokens.find((t) => `{${t.path.join('.')}}` === ref)
const px = (dictionary, v) => (typeof v === 'string' ? lookup(dictionary, v).original.$value.value : v.value)
const cssValue = (dictionary, v) =>
  typeof v === 'string' && v.startsWith('{') ? `var(--${lookup(dictionary, v).name})` : dimension(v, ROOT_PX)

/**
 * A typography role becomes one var per property. A responsive role starts at
 * its `base` step and changes at each breakpoint it names, ending at fontSize
 * from the next breakpoint on (or xl): whole steps of the scale, never a size
 * computed from the screen. letterSpacing is px at fontSize; on the web it
 * becomes em so it follows the step. The line height is rounded to a whole
 * pixel, since a ratio alone gives 29.25px.
 */
function typographyVars(dictionary, token) {
  const o = token.original.$value
  const steps = token.original.$extensions?.['world.responsive']
  const lineHeight = cssValue(dictionary, o.lineHeight)
  return [
    ['font-family', cssValue(dictionary, o.fontFamily)],
    ['font-size', cssValue(dictionary, steps?.base ?? o.fontSize)],
    ['font-weight', cssValue(dictionary, o.fontWeight)],
    ['line-height', `round(calc(${lineHeight} * 1em), 1px)`],
    ['letter-spacing', `${round(o.letterSpacing.value / px(dictionary, o.fontSize), 3)}em`],
  ].map(([prop, value]) => `  --${token.name}-${prop}: ${value};`)
}

const BREAKPOINTS = ['sm', 'md', 'lg', 'xl']

function responsiveBlocks(dictionary) {
  const roles = dictionary.allTokens.filter((t) => t.original.$extensions?.['world.responsive'])
  return BREAKPOINTS.flatMap((bp) => {
    const vars = roles.flatMap((t) => {
      const steps = t.original.$extensions['world.responsive']
      const named = BREAKPOINTS.filter((k) => steps[k])
      const final = named.length ? BREAKPOINTS[BREAKPOINTS.indexOf(named.at(-1)) + 1] : 'xl'
      const size = steps[bp] ?? (bp === final ? t.original.$value.fontSize : null)
      return size ? [`    --${t.name}-font-size: ${cssValue(dictionary, size)};`] : []
    })
    if (!vars.length) return []
    const width = lookup(dictionary, `{breakpoint.${bp}}`).$value
    return [`@media (min-width: ${width}) {`, '  :root {', ...vars, '  }', '}', '']
  })
}

StyleDictionary.registerFormat({
  name: 'css/world-base',
  format: ({ dictionary }) =>
    [
      ...HEADER('base.json'),
      '',
      ':root {',
      ...dictionary.allTokens.flatMap((t) =>
        t.$type === 'typography' ? typographyVars(dictionary, t) : [`  --${t.name}: ${t.$value};`],
      ),
      '}',
      '',
      ...responsiveBlocks(dictionary),
    ].join('\n'),
})

/**
 * One environment's colors. Vars apply on :root only while its wrapper is
 * mounted (`:root:has([data-env])`), so two environments' CSS can both be
 * loaded after a client-side navigation without clashing. The choice lives on
 * <html data-theme> (set before paint by app/layout.tsx); absent = follow the OS.
 */
StyleDictionary.registerFormat({
  name: 'css/scoped-theme',
  format: ({ dictionary, options: { theme } }) => {
    const scope = `[data-env="${theme}"]`
    const vars = (mode, indent = '  ') =>
      dictionary.allTokens
        .filter((t) => t.path[0] === theme && t.path[1] === mode)
        .map((t) => `${indent}--${t.path.slice(2).join('-')}: ${t.$value};`)

    return [
      ...HEADER(`${theme}.json`),
      '',
      `/* Applies only while ${scope} is mounted. */`,
      `:root:has(${scope}) {`,
      '  color-scheme: light;',
      ...vars('light'),
      '}',
      '',
      `:root[data-theme="dark"]:has(${scope}) {`,
      '  color-scheme: dark;',
      ...vars('dark'),
      '}',
      '',
      '/* No explicit choice stored → follow the OS. */',
      '@media (prefers-color-scheme: dark) {',
      `  :root:not([data-theme="light"]):has(${scope}) {`,
      '    color-scheme: dark;',
      ...vars('dark', '    '),
      '  }',
      '}',
      '',
      '/* Paper is the only mode that prints. Same specificity as the dark rules, declared later. */',
      '@media print {',
      `  :root:root:has(${scope}) {`,
      '    color-scheme: light;',
      ...vars('light', '    '),
      '  }',
      '}',
      '',
    ].join('\n')
  },
})

// Media queries can't read CSS vars, so Tailwind gets the breakpoints as literals.
StyleDictionary.registerFormat({
  name: 'css/tailwind-breakpoints',
  format: ({ dictionary }) =>
    [
      ...HEADER('base.json'),
      '',
      '@theme {',
      '  --breakpoint-*: initial;',
      ...dictionary.allTokens.map((t) => `  --${t.name}: ${t.$value};`),
      '}',
      '',
    ].join('\n'),
})

// The base colors are what themes extend; only the themes' roles reach CSS.
const isShared = (t) => !THEMES.includes(t.path[0]) && t.path[0] !== 'color'

const sd = new StyleDictionary({
  source: ['tokens/*.json'],
  log: { verbosity: 'default' },
  platforms: {
    css: {
      transforms: TRANSFORMS,
      buildPath: 'generated/css/',
      files: [
        { destination: 'tokens.css', format: 'css/world-base', filter: isShared },
        { destination: 'tailwind-breakpoints.css', format: 'css/tailwind-breakpoints', filter: (t) => t.path[0] === 'breakpoint' },
        ...THEMES.map((theme) => ({
          destination: `${theme}.css`,
          format: 'css/scoped-theme',
          filter: (t) => t.path[0] === theme,
          options: { theme },
        })),
      ],
    },
    json: {
      transforms: TRANSFORMS,
      buildPath: 'generated/',
      files: [{ destination: 'tokens.json', format: 'json/nested' }],
    },
  },
})

await sd.buildAllPlatforms()

// ── Brand SVGs ─────────────────────────────────────────────────────────────
// The mark from its geometry (src/mark.ts) in the built colors. Same numbers
// as the <Mark> component, so the two can never drift.
const built = JSON.parse(readFileSync('generated/tokens.json', 'utf8'))
const { light: day, dark: night } = built.portfolio
const ink = day.color.foreground
const paper = day.color.surface
const rubric = day.color.primary
const ember = night.color.primary
// The Capela's star: its ink and the rubric red (black and red, like a missal).
const chapelInk = built.chapel.light.color.foreground
const chapelRubric = built.chapel.light.color.primary
// The Blog's seed: ink and the rubric red, on the page of a book.
const blogInk = built.blog.light.color.foreground
const blogRubric = built.blog.light.color.primary

const svg = (body, extra = '') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${g.box} ${g.box}" width="${g.box * 4}" height="${g.box * 4}">${extra}${body}</svg>\n`

const mark = (color, satelliteColor, variant = 'satellite') =>
  svg(
    `<path d="${MARK_ORBIT_PATH}" fill="none" stroke="${color}" stroke-width="${g.stroke}"/>` +
      `<circle cx="${g.cx}" cy="${g.cy}" r="${g.core}" fill="${color}"/>` +
      `<path d="${markSatellitePath(variant)}" fill="${satelliteColor}"/>`,
  )

// Follows the OS: ink + rubric on light tab bars, paper + ember on dark ones.
const favicon = svg(
  `<path class="i" d="${MARK_ORBIT_PATH}" fill="none" stroke-width="${g.stroke}"/>` +
    `<circle class="f" cx="${g.cx}" cy="${g.cy}" r="${g.core}"/>` +
    `<path class="s" d="${markSatellitePath('satellite')}"/>`,
  `<style>.i{stroke:${ink}}.f{fill:${ink}}.s{fill:${rubric}}` +
    `@media (prefers-color-scheme:dark){.i{stroke:${paper}}.f{fill:${paper}}.s{fill:${ember}}}</style>`,
)

const brand = {
  'mark.svg': mark(ink, rubric),
  'mark-paper.svg': mark(paper, ember),
  'mark-mono.svg': mark(ink, ink),
  'mark-star.svg': mark(chapelInk, chapelRubric, 'star'),
  'mark-seed.svg': mark(blogInk, blogRubric, 'seed'),
  'mark-artifact.svg': mark(ink, rubric, 'artifact'),
  'favicon.svg': favicon,
}
mkdirSync('generated/brand', { recursive: true })
for (const [name, content] of Object.entries(brand)) writeFileSync(`generated/brand/${name}`, content)
console.log(`\nbrand\n✔︎ generated/brand/ (${Object.keys(brand).length} SVGs)`)
