// Builds the design tokens (DTCG 2025.10 JSON in tokens/) into what the web
// app consumes, with Style Dictionary:
//
//   generated/css/tokens.css      shared tokens on :root (type, space, size, radius, motion, layers)
//   generated/css/tailwind-breakpoints.css   the breakpoints as Tailwind @theme literals
//   generated/css/<theme>.css     one environment's colors and shadow, scoped to [data-env="<theme>"], day/night/print
//   generated/tokens.json         every resolved value, for code that needs a literal (swatches, brand SVGs)
//
//   pnpm --filter @my-world/design-system build   (or `pnpm tokens` at the root)
//
// The tokens are written in px and ms. The web is where they become responsive:
// type, space, sizes and breakpoints turn into rem (so they follow the reader's
// browser font size), and roles with a `world.fluid` extension grow with the
// viewport (clamp). Hairlines, corners and shadows stay in px.
//
// Another platform (iOS, Android, Figma…) is another entry in `platforms`.
import { readFileSync } from 'node:fs'
import StyleDictionary from 'style-dictionary'

const THEMES = ['portfolio', 'chapel']
const SOURCES = ['base', 'palette', ...THEMES]
const HEADER = (source) => [
  `/* Generated by Style Dictionary from packages/design-system/tokens/${source} — do not edit. */`,
  '/* To update: edit the JSON, then `pnpm tokens`. */',
]

// 1rem on the web = the browser's font size, 16px unless the reader changed it.
const ROOT_PX = 16
// Fluid roles reach their min at this viewport width and their max at the other.
const FLUID_FROM_PX = 360
const FLUID_TO_PX = 1280
// Token groups whose px become rem on the web.
const REM_GROUPS = ['font', 'space', 'size', 'breakpoint']

const round = (n) => +n.toFixed(4)
const rem = (px) => `${round(px / ROOT_PX)}rem`

// A DTCG color keeps both `components` (what the spec reads) and `hex` (what a
// person edits). Refuse to build if someone changed one and not the other.
function checkColors(node, path = []) {
  if (node && typeof node === 'object') {
    const v = node.$value
    if (v && typeof v === 'object' && v.hex && v.components) {
      const hex = '#' + v.components.map((c) => Math.round(c * 255).toString(16).padStart(2, '0')).join('')
      if (hex.toLowerCase() !== v.hex.toLowerCase()) {
        throw new Error(`${path.join('.')}: hex ${v.hex} doesn't match components (${hex}). Update both.`)
      }
    }
    for (const [k, child] of Object.entries(node)) if (!k.startsWith('$')) checkColors(child, [...path, k])
  }
}
for (const file of SOURCES) checkColors(JSON.parse(readFileSync(`tokens/${file}.json`, 'utf8')))

const dimension = (v, toRem) =>
  typeof v === 'object' ? (toRem && v.unit === 'px' ? rem(v.value) : `${v.value}${v.unit}`) : v

StyleDictionary.registerTransform({
  name: 'world/dimension',
  type: 'value',
  filter: (t) => t.$type === 'dimension',
  transform: (t) => dimension(t.$value, REM_GROUPS.includes(t.path[0])),
})

StyleDictionary.registerTransform({
  name: 'world/duration',
  type: 'value',
  filter: (t) => t.$type === 'duration',
  transform: (t) => `${t.$value.value}${t.$value.unit}`,
})

StyleDictionary.registerTransform({
  name: 'world/shadow',
  type: 'value',
  transitive: true,
  filter: (t) => t.$type === 'shadow',
  transform: ({ $value: s }) =>
    typeof s === 'string' ? s : [s.offsetX, s.offsetY, s.blur, s.spread].map((d) => dimension(d)).join(' ') + ` ${s.color}`,
})

const TRANSFORMS = ['name/kebab', 'world/dimension', 'world/duration', 'color/css', 'fontFamily/css', 'cubicBezier/css', 'world/shadow']

// `{font.size.9xl}` → the token it points to.
const lookup = (dictionary, ref) => dictionary.allTokens.find((t) => `{${t.path.join('.')}}` === ref)
const cssVar = (dictionary, ref) => `var(--${lookup(dictionary, ref).name})`
const px = (dictionary, ref) => lookup(dictionary, ref).original.$value.value

// clamp(min, a + b·vw, max): min at FLUID_FROM_PX, max at FLUID_TO_PX.
function fluid(minPx, maxPx) {
  const slope = (maxPx - minPx) / (FLUID_TO_PX - FLUID_FROM_PX)
  const intercept = minPx - slope * FLUID_FROM_PX
  return `clamp(${rem(minPx)}, ${rem(intercept)} + ${round(slope * 100)}vw, ${rem(maxPx)})`
}

/** A typography role becomes one var per property, pointing at the scale's vars. */
function typographyVars(dictionary, token) {
  const o = token.original.$value
  const min = token.original.$extensions?.['world.fluid']?.min
  const size = min ? fluid(px(dictionary, min), px(dictionary, o.fontSize)) : cssVar(dictionary, o.fontSize)
  return [
    ['font-family', cssVar(dictionary, o.fontFamily)],
    ['font-size', size],
    ['font-weight', cssVar(dictionary, o.fontWeight)],
    ['line-height', cssVar(dictionary, o.lineHeight)],
    ['letter-spacing', cssVar(dictionary, o.letterSpacing)],
  ].map(([prop, value]) => `  --${token.name}-${prop}: ${value};`)
}

StyleDictionary.registerFormat({
  name: 'css/world-base',
  format: ({ dictionary }) =>
    [
      ...HEADER('base.json'),
      '',
      ':root {',
      ...dictionary.allTokens.flatMap((t) =>
        t.$type === 'typography' ? typographyVars(dictionary, t) : [`  --${t.name}: ${t.$value};`],
      ),
      '}',
      '',
    ].join('\n'),
})

/**
 * One environment's colors. Vars apply on :root only while its wrapper is
 * mounted (`:root:has([data-env])`), so two environments' CSS can both be
 * loaded after a client-side navigation without clashing. The choice lives on
 * <html data-theme> (set before paint by app/layout.tsx); absent = follow the OS.
 */
StyleDictionary.registerFormat({
  name: 'css/scoped-theme',
  format: ({ dictionary, options: { theme } }) => {
    const scope = `[data-env="${theme}"]`
    const vars = (mode, indent = '  ') =>
      dictionary.allTokens
        .filter((t) => t.path[0] === theme && t.path[1] === mode)
        .map((t) => `${indent}--${t.path.slice(2).join('-')}: ${t.$value};`)

    return [
      ...HEADER(`${theme}.json`),
      '',
      `/* Applies only while ${scope} is mounted. */`,
      `:root:has(${scope}) {`,
      '  color-scheme: light;',
      ...vars('light'),
      '}',
      '',
      `:root[data-theme="dark"]:has(${scope}) {`,
      '  color-scheme: dark;',
      ...vars('dark'),
      '}',
      '',
      '/* No explicit choice stored → follow the OS. */',
      '@media (prefers-color-scheme: dark) {',
      `  :root:not([data-theme="light"]):has(${scope}) {`,
      '    color-scheme: dark;',
      ...vars('dark', '    '),
      '  }',
      '}',
      '',
      '/* Paper is the only mode that prints. Same specificity as the dark rules, declared later. */',
      '@media print {',
      `  :root:root:has(${scope}) {`,
      '    color-scheme: light;',
      ...vars('light', '    '),
      '  }',
      '}',
      '',
    ].join('\n')
  },
})

// Media queries can't read CSS vars, so Tailwind gets the breakpoints as literals.
StyleDictionary.registerFormat({
  name: 'css/tailwind-breakpoints',
  format: ({ dictionary }) =>
    [
      ...HEADER('base.json'),
      '',
      '@theme {',
      '  --breakpoint-*: initial;',
      ...dictionary.allTokens.map((t) => `  --${t.name}: ${t.$value};`),
      '}',
      '',
    ].join('\n'),
})

const isShared = (t) => !THEMES.includes(t.path[0]) && t.path[0] !== 'palette'

const sd = new StyleDictionary({
  source: ['tokens/*.json'],
  log: { verbosity: 'default' },
  platforms: {
    css: {
      transforms: TRANSFORMS,
      buildPath: 'generated/css/',
      files: [
        { destination: 'tokens.css', format: 'css/world-base', filter: isShared },
        { destination: 'tailwind-breakpoints.css', format: 'css/tailwind-breakpoints', filter: (t) => t.path[0] === 'breakpoint' },
        ...THEMES.map((theme) => ({
          destination: `${theme}.css`,
          format: 'css/scoped-theme',
          filter: (t) => t.path[0] === theme,
          options: { theme },
        })),
      ],
    },
    json: {
      transforms: TRANSFORMS,
      buildPath: 'generated/',
      files: [{ destination: 'tokens.json', format: 'json/nested' }],
    },
  },
})

await sd.buildAllPlatforms()
